CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (length(trim(name)) > 0),
    description varchar(2000),
    team_id bigint NOT NULL REFERENCES teams (id),
    status varchar(20) NOT NULL CHECK (status IN ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED')),
    start_date date,
    end_date date,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT ck_projects_dates CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX idx_projects_team_status ON projects (team_id, status, id);
CREATE INDEX idx_team_members_user ON team_members (user_id, team_id);
