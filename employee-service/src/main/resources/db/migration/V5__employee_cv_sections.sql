CREATE TABLE employee_skill (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES employee_profile(user_id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    proficiency varchar(30) NOT NULL CHECK (proficiency IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')),
    years_of_experience numeric(4,1) NOT NULL CHECK (years_of_experience BETWEEN 0 AND 100)
);
CREATE INDEX employee_skill_user_idx ON employee_skill(user_id);
CREATE TABLE employee_education (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES employee_profile(user_id) ON DELETE CASCADE,
    institution varchar(200) NOT NULL,
    qualification varchar(200) NOT NULL,
    field_of_study varchar(200),
    start_year integer NOT NULL CHECK (start_year BETWEEN 1900 AND 2200),
    end_year integer CHECK (end_year BETWEEN start_year AND 2200),
    grade varchar(100)
);
CREATE INDEX employee_education_user_idx ON employee_education(user_id);
CREATE TABLE employee_experience (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES employee_profile(user_id) ON DELETE CASCADE,
    company varchar(200) NOT NULL,
    title varchar(200) NOT NULL,
    start_date date NOT NULL,
    end_date date,
    description varchar(5000),
    is_current boolean NOT NULL,
    CHECK ((is_current AND end_date IS NULL) OR (NOT is_current AND end_date >= start_date AND end_date IS NOT NULL))
);
CREATE INDEX employee_experience_user_idx ON employee_experience(user_id);
ALTER TABLE employee_profile
    ADD COLUMN cv_object_key varchar(255),
    ADD COLUMN pending_cv_key varchar(255),
    ADD COLUMN pending_cv_type varchar(100),
    ADD COLUMN pending_cv_size bigint,
    ADD COLUMN pending_cv_expires_at timestamp(6) with time zone;
